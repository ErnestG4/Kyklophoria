#!/usr/bin/env python3
"""Emit core/kyk_tables.h: a float32 sine table as hex-float literals.

The table is the only source of trig in the core (FFT twiddles, derived
harmonic phases), so the desktop and the module see bit-identical constants
without trusting two libm's. Re-run after changing kTableSize; commit the
result."""
import math, struct, sys
SIZE = 2048
def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]
out = []
out.append('/* Generated by tools/gen/gen_tables.py — do not edit. */')
out.append('#pragma once')
out.append('namespace kyk {')
out.append('constexpr int kTableSize = %d;   /* one full period */' % SIZE)
out.append('constexpr int kTableLog2 = %d;' % int(math.log2(SIZE)))
out.append('/* sin(2*pi*i/kTableSize), rounded to float32. cos(x) = sin(x + kTableSize/4). */')
out.append('static const float kSinTable[kTableSize] = {')
row = []
for i in range(SIZE):
    v = f32(math.sin(2.0 * math.pi * i / SIZE))
    # exact quarter points
    if i % (SIZE // 4) == 0:
        v = [0.0, 1.0, 0.0, -1.0][i // (SIZE // 4)]
    row.append(v.hex() + 'f')
    if len(row) == 4:
        out.append('    ' + ', '.join(row) + ',')
        row = []
out.append('};')

# Natural logs and reciprocals of the harmonic numbers 1..kMaxK.
#
# The vowel world needs ln(h) and 1/h for every harmonic on every evaluation,
# and the core's Ln and Exp are series: computing them cost 256 series
# evaluations per spectrum and made that world twelve times more expensive
# than any other. They are the same 64 numbers every time, so they are
# constants, and constants belong here with the sine table where both targets
# see identical bits.
MAXK = 128
out.append('')
out.append('/* ln(h) and 1/h for harmonics h = 1..kMaxK, rounded to float32. */')
out.append('static const float kLnHarm[%d] = {' % MAXK)
row = []
for i in range(MAXK):
    row.append(f32(math.log(i + 1)).hex() + 'f')
    if len(row) == 4:
        out.append('    ' + ', '.join(row) + ',')
        row = []
out.append('};')
out.append('static const float kInvHarm[%d] = {' % MAXK)
row = []
for i in range(MAXK):
    row.append(f32(1.0 / (i + 1)).hex() + 'f')
    if len(row) == 4:
        out.append('    ' + ', '.join(row) + ',')
        row = []
out.append('};')

# Two more harmonic laws, so a tilt can brighten without turning the waveform
# into an impulse. An exponential tilt r^h stops the series falling once r
# exceeds one, and a series that does not fall is a spike: measured crest 4.07
# on that axis alone and 6.76 in the corner, against the 4.3 the output gain
# allows. h^-q always falls, whatever q, so the crest stays put — and blending
# between three fixed exponents needs no power function at run time.
for name, q in (('kInvHarmHalf', 0.75), ('kInvHarmSteep', 1.6)):
    out.append('')
    out.append('/* h^-%.2f for harmonics h = 1..kMaxK. */' % q)
    out.append('static const float %s[%d] = {' % (name, MAXK))
    row = []
    for i in range(MAXK):
        row.append(f32((i + 1) ** -q).hex() + 'f')
        if len(row) == 4:
            out.append('    ' + ', '.join(row) + ',')
            row = []
    out.append('};')
out.append('} // namespace kyk')
sys.stdout.write('\n'.join(out) + '\n')
